"""Real browser checks against the isolated acceptance server only; no model calls."""
import json
import uuid
import hashlib
from pathlib import Path
from playwright.sync_api import sync_playwright,expect

root=Path(__file__).resolve().parents[1]
out=root/'storage'/'release-verification'/('ui-closeout-'+uuid.uuid4().hex)
out.mkdir(parents=True,exist_ok=True)
checks=[]
with sync_playwright() as pw:
    browser=pw.chromium.launch(channel='chrome',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':960})
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:8876/')
    expect(page.locator('.product-table tbody tr')).to_have_count(352)
    health=page.request.get('http://127.0.0.1:8876/api/health').json()
    assert 'release-verification' in health['storage']
    page.get_by_role('button',name='筛选 件数标签',exact=True).click()
    panel=page.locator('.filter-editor')
    expect(panel).to_be_visible()
    panel.get_by_role('button',name='清空勾选',exact=True).click()
    panel.get_by_role('button',name='应用筛选',exact=True).click()
    expect(page.locator('.product-table tbody tr')).to_have_count(0)
    checks.append('empty value selection returns zero rows')
    page.get_by_role('button',name='筛选 件数标签',exact=True).click()
    panel.get_by_role('button',name='清除此列筛选',exact=True).click()
    expect(page.locator('.product-table tbody tr')).to_have_count(352)
    page.get_by_role('button',name='筛选 件数标签',exact=True).click()
    panel.get_by_label('筛选关键词',exact=True).fill('2')
    panel.get_by_role('button',name='应用筛选',exact=True).click()
    count=page.locator('.product-table tbody tr').count()
    assert 0<count<352
    expect(page.locator('th.filtered-column')).to_have_count(1)
    checks.append({'keyword_filter_rows':count,'header_mark':True})
    page.get_by_role('button',name='筛选 · 1列',exact=True).click()
    panel.get_by_label('筛选字段',exact=True).select_option(label='件数标签')
    expect(panel.get_by_label('筛选关键词',exact=True)).to_have_value('2')
    panel.get_by_label('关闭筛选',exact=True).click()
    checks.append('toolbar and header filters share the same state')
    before=page.evaluate("Object.fromEntries(Object.entries(localStorage).filter(([k])=>k.startsWith('worksheet:')))")
    page.get_by_label('查看版本',exact=True).select_option(label='V1')
    expect(page.locator('.product-table tbody tr')).to_have_count(352)
    page.get_by_label('统一行高',exact=True).fill('48')
    page.get_by_label('查看版本',exact=True).select_option(value='')
    expect(page.locator('.product-table tbody tr')).to_have_count(count)
    expect(page.get_by_label('统一行高',exact=True)).to_have_value('80')
    after=page.evaluate("Object.fromEntries(Object.entries(localStorage).filter(([k])=>k.startsWith('worksheet:')))")
    assert before==after,(before,after)
    checks.append('version browsing restores draft filters and layout without changing saved preferences')
    page.get_by_role('button',name='表格专注',exact=True).click()
    expect(page.locator('.workbench')).to_have_class('workbench table-focus')
    page.get_by_label('统一行高',exact=True).fill('120')
    page.get_by_label('统一行高',exact=True).press('Tab')
    height=page.locator('.product-table tbody tr').first.evaluate('(row)=>row.getBoundingClientRect().height')
    assert height>=120,height
    page.reload()
    expect(page.locator('.product-table tbody tr')).to_have_count(count)
    expect(page.get_by_label('统一行高',exact=True)).to_have_value('120')
    page.get_by_role('button',name='表格专注',exact=True).click()
    checks.append({'uniform_row_height':height,'preferences_survive_reload':True})
    page.locator('.product-table tbody img').first.dblclick()
    viewer=page.get_by_role('dialog',name='商品原图')
    expect(viewer).to_be_visible()
    page.wait_for_function("document.querySelector('.image-stage img')?.naturalWidth > 0")
    viewer.get_by_role('button',name='100%原始尺寸',exact=True).click()
    page.wait_for_timeout(100)
    dims=page.locator('.image-stage img').evaluate('(im)=>({natural:im.naturalWidth,display:im.getBoundingClientRect().width})')
    assert abs(dims['natural']-dims['display'])<1,dims
    viewer.get_by_role('button',name='下一件 →',exact=True).click()
    page.keyboard.press('Escape')
    expect(viewer).to_have_count(0)
    expect(page.locator('.workbench')).to_have_class('workbench table-focus')
    page.keyboard.press('Escape')
    expect(page.locator('.workbench')).to_have_class('workbench ')
    checks.append({'original_size':dims,'escape_preserves_focus_first':True})
    page.get_by_label('搜索商品',exact=True).fill('NO_MATCH_ACCEPTANCE')
    expect(page.locator('.product-table tbody tr')).to_have_count(0)
    page.get_by_label('数据集',exact=True).select_option(label='测试10行')
    expect(page.locator('.product-table tbody tr')).to_have_count(10)
    expect(page.get_by_label('搜索商品',exact=True)).to_have_value('')
    checks.append('dataset switch clears previous search and scoped UI')
    page.screenshot(path=str(out/'worksheet.png'),full_page=False)
    assert not errors,errors
    (out/'report.json').write_text(json.dumps({'health':health,'frontend_sha256':{str(p.relative_to(root)):hashlib.sha256(p.read_bytes()).hexdigest() for p in (root/'storage/release-verification/0.4.1/frontend-dist').rglob('*') if p.is_file()},'checks':checks,'page_errors':errors,'model_requests':0},ensure_ascii=False,indent=2),encoding='utf-8')
    browser.close()
print(json.dumps({'report':str(out/'report.json'),'checks':checks},ensure_ascii=True))
